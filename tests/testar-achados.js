"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Achados = require('../src/data/AchadosPerdidos');
const Menu = require('../src/services/MenuService');
const Chat = require('../src/services/ChatbotService');
const pasta = fs.mkdtempSync(path.join(os.tmpdir(),'cotrami-ap-'));
try {
  const achados = new Achados(path.join(pasta,'ap.json'));
  const estados=new Map();
  const sessao={ definir:(u,v)=>estados.set(u,v),obter:u=>estados.get(u),existe:u=>estados.has(u) };
  const db={listar:()=>[]};
  const escalas={listar:()=>[]};
  const bot = new Chat(new Menu(),sessao,db,escalas,achados);
  const send=(u,m)=>bot.processarMensagem(u,m);
  assert.match(send('5511988880000@c.us','6'),/ACHADOS E PERDIDOS/);
  assert.match(send('5511988880000@c.us','1'),/Descreva o objeto/);
  send('5511988880000@c.us','mochila preta');
  send('5511988880000@c.us','hoje às 8h');
  send('5511988880000@c.us','18');
  const confirmado=send('5511988880000@c.us','1');
  assert.match(confirmado,/OCORRÊNCIA REGISTRADA/);
  const protocolo=confirmado.match(/AP-[A-F0-9]{12}/)[0];
  assert.equal(achados.listar().length,1);
  assert.equal(achados.listar()[0].descricao,'mochila preta');
  send('5511988880000@c.us','7');
  assert.match(send('5511988880000@c.us',protocolo),/Aberto/);
  send('5511977770000@c.us','7');
  assert.match(send('5511977770000@c.us',protocolo),/não encontrado/);
  achados.atualizar(protocolo,'em_analise','aguardando contato','admin');
  send('5511988880000@c.us','7');
  const ret=send('5511988880000@c.us',protocolo);
  assert.match(ret,/Em análise/);
  assert.doesNotMatch(ret,/aguardando contato/);
  assert.match(send('5511988880000@c.us','0'),/COTRAMI/);
  assert.throws(()=>achados.atualizar(protocolo,'qualquer','x','admin'));
  console.log('OK: abertura, persistência, consulta restrita ao autor, histórico e atualização de status.');
} finally {fs.rmSync(pasta,{recursive:true,force:true});}
